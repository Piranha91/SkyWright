"""Known answers for ruling 12: every probe refuses an order whose plugin lacks a master, in one sentence, exit 2.

    python _geometry-harness/tests/test_missing_master_refusal.py

Drives the REAL built probes against a temporary MO2 layout written here (never a real install):

    game/Data/Base.esm                  master-flagged, no masters
    instance/mods/ModP/Parent.esp       masters Base.esm
    instance/mods/ModC/Child.esp        masters Base.esm and Parent.esp
    profile Bad      Child.esp ticked, Parent.esp unticked  -> Child lacks a master
    profile NoParent Base.esm only (Parent and Child not in loadorder.txt), for switchprobe --extra-plugin Child.esp

Cases (numbers 356-358; 350-355 are the reader-level cases in proofprobe's ConfigurationProof):
    356  every probe that reads its order through HarnessOrderCli.Resolve: exit 2, the sentence exactly once, nothing
         written to its working folder. The row count is asserted.
    357  the probes that build the order themselves (Mo2LoadOrder.Build), and switchprobe's --extra-plugin: the same.
    358  orderprobe refuses before any search; scopeprobe prints one refusal, no walk-failure line, no scope.json.

The sentence is `MISSING MASTER - 'Child.esp' masters 'Parent.esp', which this order does not load, ...`. A missing
Release exe is a FAILURE, never a skip. Exit 0 when every case passes.
"""
from __future__ import annotations

import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
HARNESS = HERE.parent
sys.path.append(str(HARNESS))
import buildlayout  # noqa: E402  where the build put each program
FAILURES: list[str] = []
PASSED: list[str] = []
SENTENCE = "MISSING MASTER - 'Child.esp' masters 'Parent.esp', which this order does not load"


def check(ok: bool, label: str, detail: str = "") -> None:
    (PASSED if ok else FAILURES).append(label)
    print(("PASS " if ok else "FAIL ") + label + ("" if ok or not detail else "\n      " + detail.replace("\n", "\n      ")))


def exe(name: str) -> Path:
    """The program in this checkout's build (buildlayout)."""
    return buildlayout.program(name)


def plugin(path: Path, masters: list[str], esm: bool = False) -> None:
    """A TES4-only plugin: HEDR, then MAST/DATA per master. Enough for every header read and for an overlay open."""
    body = b"HEDR" + struct.pack("<H", 12) + struct.pack("<fiI", 1.7, 0, 0x800)
    for m in masters:
        z = m.encode("latin-1") + b"\0"
        body += b"MAST" + struct.pack("<H", len(z)) + z + b"DATA" + struct.pack("<H", 8) + struct.pack("<Q", 0)
    head = b"TES4" + struct.pack("<IIIIHH", len(body), 1 if esm else 0, 0, 0, 44, 0)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(head + body)


def profile(inst: Path, name: str, modlist: list[str], loadorder: list[str], plugins: list[str]) -> None:
    d = inst / "profiles" / name
    d.mkdir(parents=True, exist_ok=True)
    head = "# This file was automatically generated by Mod Organizer.\n"
    (d / "modlist.txt").write_text(head + "\n".join(modlist) + "\n", encoding="utf-8")
    (d / "loadorder.txt").write_text(head + "\n".join(loadorder) + "\n", encoding="utf-8")
    (d / "plugins.txt").write_text(head + "\n".join(plugins) + "\n", encoding="utf-8")


def candidate(path: Path, plugins: list[str], mods: list[str]) -> Path:
    path.write_text(json.dumps({"SchemaVersion": 1, "Name": path.stem, "BaseProfile": "Bad", "Plugins": plugins,
                                "Mods": mods, "Changes": []}), encoding="utf-8")
    return path


def run(probe: str, args: list[str], tmp: Path, prof: str, inst: Path, game: Path, work: Path) -> tuple[int, str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith("HOUSECARL_MO2") and k != "HOUSECARL_GAME_PATH"}
    env.update({"HOUSECARL_HARNESS_CONFIG": str(tmp / "harness.json"), "HOUSECARL_RUNLOG_DIR": str(tmp / "runlog"),
                "HOUSECARL_MO2_INSTANCE": inst.as_posix(), "HOUSECARL_MO2_PROFILE": prof,
                "HOUSECARL_GAME_PATH": game.as_posix()})
    work.mkdir(parents=True, exist_ok=True)
    try:
        p = subprocess.run([str(exe(probe))] + args, env=env, cwd=work, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=180)
        return p.returncode, (p.stdout or "") + (p.stderr or "")
    except subprocess.TimeoutExpired as ex:
        return -1, f"timeout: {ex}"


def written(work: Path) -> list[str]:
    return sorted(str(p.relative_to(work)) for p in work.rglob("*") if p.is_file())


def stamps(probe: str) -> dict[str, float]:
    """The probe's own bin folder (geoprobe writes its result next to its exe)."""
    d = exe(probe).parent
    return {str(p): p.stat().st_mtime for p in d.rglob("*") if p.is_file()} if d.exists() else {}


def touched(before: dict[str, float], after: dict[str, float]) -> list[str]:
    return sorted(Path(k).name for k, v in after.items() if before.get(k) != v)


def main() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="hc-missing-master-"))
    try:
        inst, game = tmp / "instance", tmp / "game"
        plugin(game / "Data" / "Base.esm", [], esm=True)
        plugin(game / "Data" / "Skyrim.esm", [], esm=True)   # navprobe opens it by name before the order; not loaded
        plugin(inst / "mods" / "ModP" / "Parent.esp", ["Base.esm"])
        plugin(inst / "mods" / "ModC" / "Child.esp", ["Base.esm", "Parent.esp"])
        (inst / "overwrite").mkdir(parents=True)
        (inst / "ModOrganizer.ini").write_text(f"[General]\ngamePath=@ByteArray({str(game)})\n", encoding="utf-8")
        (tmp / "harness.json").write_text(json.dumps({"instance": inst.as_posix(), "profile": "Bad",
                                                      "game": game.as_posix()}), encoding="utf-8")
        mods = ["+ModC", "+ModP"]
        profile(inst, "Bad", mods, ["Base.esm", "Parent.esp", "Child.esp"], ["Parent.esp", "*Child.esp"])
        profile(inst, "NoParent", mods, ["Base.esm"], [])
        cand = candidate(tmp / "child-without-parent.json", ["Base.esm", "Child.esp"], ["ModC", "ModP"])
        child = inst / "mods" / "ModC" / "Child.esp"
        pin = ["--instance", inst.as_posix(), "--game", game.as_posix(), "--profile", "Bad"]

        # (case, probe, profile, args): every argument a probe needs before it reads its order, and an output path
        # inside its own working folder wherever it takes one, so "nothing written" is checked on the real flag.
        rows356 = [
            ("bosprobe", "Bad", []),
            ("contactprobe", "Bad", ["--emit", "out.json"]),
            ("depprobe", "Bad", ["--json", "out.json"]),
            ("driftprobe", "Bad", ["--emit", "out.json"]),
            ("navownprobe", "Bad", ["--emit", "out.json"]),
            ("overlapprobe", "Bad", ["--emit", "out.json"]),
            ("seamprobe", "Bad", ["--json", "out.json"]),
            ("stateprobe", "Bad", ["--all", "--json", "out.json"]),
            ("switchprobe", "Bad", ["--json", "out.json"]),
            ("waterprobe", "Bad", ["--json", "out.json"]),
            ("scopeprobe", "Bad", ["--target", "Child.esp", "--json", "scope.json"]),
            ("lightprobe", "Bad", ["--json", "out.json", "--list-interiors"]),
            ("blockprobe", "Bad", ["Child.esp", "--order", str(cand)]),
            ("floorgapprobe", "Bad", ["cell", "AnyCell", "--winning", "--order", str(cand)]),
            ("motionprobe", "Bad", pin + ["--order", str(cand), "inspect", "meshes/x.nif"]),
            ("selectprobe", "Bad", ["--newcomer", str(child), "--order", str(cand), "--out", "sel"]),
            ("leftbehindprobe", "Bad", ["--base-order", str(cand), "--city-order", str(cand), "--panel-plugin",
                                        "Child.esp", "--json", "out.json"] + pin),
            ("viewprobe", "Bad", ["AnyCell", "--order", str(cand), "--out", "view"]),
        ]
        rows357 = [
            ("viewprobe", "Bad", ["AnyCell", "--out", "view"]),
            ("viewprobe", "Bad", ["AnyCell", "--out", "view", "--config-identity"]),
            ("blockprobe", "Bad", ["Child.esp"]),
            ("floorgapprobe", "Bad", ["cell", "AnyCell", "--winning"]),
            ("geoprobe", "Bad", []),
            ("corridorprobe", "Bad", ["cut", "AnyCell"]),
            ("navprobe", "Bad", ["--bos", "on"]),
            ("switchprobe", "NoParent", ["--extra-plugin", str(child), "--json", "out.json"]),
        ]

        for case, rows, want in (("356", rows356, 18), ("357", rows357, 8)):
            check(len(rows) == want, f"{case} row count is {want}", f"{len(rows)} rows")
            for i, (probe, prof, args) in enumerate(rows):
                label = f"{case} {probe} {' '.join(a for a in args if not a.startswith(str(tmp)))}".strip()
                if not exe(probe).exists():
                    check(False, label + ": Release build exists", str(exe(probe)))
                    continue
                work = tmp / "work" / f"{case}-{i:02d}-{probe}"
                before = stamps(probe)
                code, out = run(probe, args, tmp, prof, inst, game, work)
                n = out.count(SENTENCE)
                files = written(work) + touched(before, stamps(probe))
                check(code == 2 and n == 1 and not files and "Unhandled exception" not in out,
                      f"{label}: exit 2, the sentence once, nothing written",
                      f"exit {code}; sentence x{n}; written {files}\n{out[-1200:]}")

        # 358 orderprobe: refused before any search, nothing in its --out.
        work = tmp / "work" / "358-orderprobe"
        code, out = run("orderprobe", ["--out", "o"], tmp, "Bad", inst, game, work)
        check(code == 2 and out.count(SENTENCE) == 1 and not written(work) and "contention" not in out.lower(),
              "358 orderprobe: a baseline lacking a master is refused before the search (exit 2, sentence once, no output)",
              f"exit {code}; written {written(work)}\n{out[-1200:]}")
        # 358 scopeprobe: one refusal, REFUSED-prefixed, no walk failure, no scope.json.
        work = tmp / "work" / "358-scopeprobe"
        code, out = run("scopeprobe", ["--target", "Child.esp", "--json", "scope.json"], tmp, "Bad", inst, game, work)
        check(code == 2 and out.count("REFUSED: " + SENTENCE) == 1 and out.count("MISSING MASTER") == 1
              and "walk failure" not in out and not list(work.rglob("scope.json")),
              "358 scopeprobe: 'REFUSED: MISSING MASTER - ...' once, no walk-failure line, no scope.json, exit 2",
              f"exit {code}\n{out[-1200:]}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    print(f"\n{len(PASSED)} passed, {len(FAILURES)} failed")
    return 1 if FAILURES else 0


if __name__ == "__main__":
    sys.exit(main())
