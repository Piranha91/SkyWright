"""Known answers for where corridorprobe finds its --plugin: the game's Data folder first, else the profile's load order.

    python _geometry-harness/tests/test_corridorprobe_plugin_lookup.py

A mod's plugin lives in its MO2 mod folder, not in the game's Data, so only the profile's order knows its path. Until
2026-11-27 `corridorprobe map|width|cut` opened Data\\<plugin> and nothing else: `--plugin <a mod's plugin>` ended in an
unhandled FileNotFoundException. The lookup is PluginOpen.Locate (_shared/PluginOpen.cs), the rule floorgapprobe
already followed; both probes now call it.

Drives the REAL built corridorprobe against a temporary MO2 layout written here (never a real install). The plugins
are TES4 headers only, so a found plugin answers "cell ... not found in <plugin>" (exit 1): that sentence is the proof
the file was found and opened, since it is printed only after the open.

    game/Data/Skyrim.esm, InData.esp       master / plain plugin in Data
    instance/mods/ModA/ModPlug.esp         a mod's plugin, enabled in profile P
    instance/mods/ModB/Damaged.esp         not a plugin (text), enabled in profile P

    L1  --plugin ModPlug.esp   found through the order: exit 1, "cell 'NoSuchCell' not found in ModPlug.esp"
    L2  --plugin InData.esp    found in Data (Data first): exit 1, the same sentence for InData.esp
    L3  --plugin Missing.esp   in neither: exit 2, one sentence naming it and both places looked
    L4  --plugin Damaged.esp   found, unreadable: exit 2, the PluginOpen refusal naming the file
Every case: no "Unhandled exception" in the output. A missing build is a FAILURE, never a skip. Exit 0 when all pass.
"""
from __future__ import annotations

import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
HARNESS = HERE.parent
sys.path.append(str(HARNESS))
import buildlayout  # noqa: E402  where the build put each program
FAILURES: list[str] = []
PASSED: list[str] = []


def check(ok: bool, label: str, detail: str = "") -> None:
    (PASSED if ok else FAILURES).append(label)
    print(("PASS " if ok else "FAIL ") + label + ("" if ok or not detail else "\n      " + detail.replace("\n", "\n      ")))


def plugin(path: Path, masters: list[str], esm: bool = False) -> None:
    """A TES4-only plugin: HEDR, then MAST/DATA per master (the same header test_missing_master_refusal.py writes)."""
    body = b"HEDR" + struct.pack("<H", 12) + struct.pack("<fiI", 1.7, 0, 0x800)
    for m in masters:
        z = m.encode("latin-1") + b"\0"
        body += b"MAST" + struct.pack("<H", len(z)) + z + b"DATA" + struct.pack("<H", 8) + struct.pack("<Q", 0)
    head = b"TES4" + struct.pack("<IIIIHH", len(body), 1 if esm else 0, 0, 0, 44, 0)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(head + body)


def main() -> int:
    exe = buildlayout.program("corridorprobe")
    if not exe.exists():
        check(False, "corridorprobe build exists", str(exe))
        return 1
    tmp = Path(tempfile.mkdtemp(prefix="sw-corridor-plugin-"))
    try:
        inst, game = tmp / "instance", tmp / "game"
        data = game / "Data"
        plugin(data / "Skyrim.esm", [], esm=True)
        plugin(data / "InData.esp", ["Skyrim.esm"])
        plugin(inst / "mods" / "ModA" / "ModPlug.esp", ["Skyrim.esm"])
        (inst / "mods" / "ModB").mkdir(parents=True)
        (inst / "mods" / "ModB" / "Damaged.esp").write_text("this is not a plugin\n", encoding="utf-8")
        (inst / "overwrite").mkdir(parents=True)
        prof = inst / "profiles" / "P"
        prof.mkdir(parents=True)
        head = "# This file was automatically generated by Mod Organizer.\n"
        (prof / "modlist.txt").write_text(head + "+ModB\n+ModA\n", encoding="utf-8")
        (prof / "loadorder.txt").write_text(head + "Skyrim.esm\nInData.esp\nModPlug.esp\nDamaged.esp\n", encoding="utf-8")
        (prof / "plugins.txt").write_text(head + "*InData.esp\n*ModPlug.esp\n*Damaged.esp\n", encoding="utf-8")
        (inst / "ModOrganizer.ini").write_text(f"[General]\ngamePath=@ByteArray({game})\n", encoding="utf-8")
        (tmp / "harness.json").write_text(json.dumps({"instance": inst.as_posix(), "profile": "P", "game": game.as_posix()}),
                                          encoding="utf-8")
        env = {k: v for k, v in os.environ.items() if not k.startswith("HOUSECARL_MO2") and k != "HOUSECARL_GAME_PATH"}
        env.update({"HOUSECARL_HARNESS_CONFIG": str(tmp / "harness.json"), "HOUSECARL_RUNLOG_DIR": str(tmp / "runlog"),
                    "HOUSECARL_MO2_INSTANCE": inst.as_posix(), "HOUSECARL_MO2_PROFILE": "P",
                    "HOUSECARL_GAME_PATH": game.as_posix()})

        def run(name: str) -> tuple[int, str]:
            try:
                p = subprocess.run([str(exe), "map", "NoSuchCell", "--plugin", name], env=env, cwd=tmp, capture_output=True,
                                   text=True, encoding="utf-8", errors="replace", timeout=120)
                return p.returncode, (p.stdout or "") + (p.stderr or "")
            except subprocess.TimeoutExpired as ex:
                return -1, f"timeout: {ex}"

        for case, name, want_exit, want in [
            ("L1", "ModPlug.esp", 1, "cell 'NoSuchCell' not found in ModPlug.esp"),
            ("L2", "InData.esp", 1, "cell 'NoSuchCell' not found in InData.esp"),
            ("L3", "Missing.esp", 2, f"Missing.esp is neither in {data} nor in the profile's load order"),
            ("L4", "Damaged.esp", 2, "Damaged.esp could not be read by corridorprobe"),
        ]:
            code, out = run(name)
            unhandled = "Unhandled exception" in out
            check(code == want_exit and want in out and not unhandled,
                  f"{case} --plugin {name}: exit {want_exit}, '{want}', no unhandled exception",
                  f"exit {code}{', UNHANDLED EXCEPTION' if unhandled else ''}; output:\n{out.strip()[-900:]}")
            if case == "L3":
                n = out.count("is neither in")
                check(n == 1, f"L3 the refusal is printed exactly once (found {n})")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print(f"\n{len(PASSED)} passed, {len(FAILURES)} failed")
    return 1 if FAILURES else 0


if __name__ == "__main__":
    sys.exit(main())
