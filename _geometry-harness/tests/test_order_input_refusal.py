"""Known answers: a probe refuses a requested order it cannot build as asked, in one sentence, exit 2 (cases 1320-1324).

    python _geometry-harness/tests/test_order_input_refusal.py

Two requests the shared order reader (_shared/HarnessOrderCli.cs) used to answer with a different order:

    --enable P   where loadorder.txt does not list P: the run went on without P and only warned.
    --order C    where C's BaseProfile is not --profile: C was resolved through the other profile's lists, silently.

Drives the REAL built probes against a temporary MO2 layout written here (never a real install):

    game/Data/Base.esm                  master-flagged, no masters
    instance/mods/ModP/Parent.esp       masters Base.esm
    instance/mods/ModC/Child.esp        masters Base.esm and Parent.esp
    instance/mods/ModG/Ghost.esp        masters Base.esm; installed, but loadorder.txt does not list it
    instance/mods/ModG/Off.esp          masters Base.esm; listed in loadorder.txt, unticked (the control --enable)
    profile Good    Base, Parent, Child ticked; mods ModG, ModC, ModP
    profile Other   the same plugins, mod priority reversed (ModP above ModC)
    cand-other.json BaseProfile 'Other', run under --profile Good
    cand-good.json  BaseProfile 'Good' (the control)

Cases (1300-1313 are the reader-level cases in proofprobe's ConfigurationProof):
    1320  every probe that takes --enable: `--enable Ghost.esp` -> exit 2, the CANNOT ENABLE sentence exactly once, nothing
          written. The row count is asserted.
    1321  every probe that reads --order through HarnessOrderCli.Resolve: cand-other.json under --profile Good -> exit 2,
          the PROFILE MISMATCH sentence exactly once, nothing written. The row count is asserted.
    1322  overlapprobe's scene preflight already refuses the mismatch before the reader: still one refusal, not two.
    1323  controls: `--enable Off.esp` and cand-good.json are not refused for either reason.
    1324  evalrun's and ordersweep's refusal markers recognise both sentences, as they do MISSING MASTER.

A missing Release exe is a FAILURE, never a skip. Exit 0 when every case passes.
"""
from __future__ import annotations

import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
HARNESS = HERE.parent
FAILURES: list[str] = []
PASSED: list[str] = []
ENABLE_SENTENCE = "CANNOT ENABLE - 'Ghost.esp' has no load-order position: loadorder.txt does not list it"
PROFILE_SENTENCE = "PROFILE MISMATCH - candidate BaseProfile 'Other' does not match --profile 'Good'"


def check(ok: bool, label: str, detail: str = "") -> None:
    (PASSED if ok else FAILURES).append(label)
    print(("PASS " if ok else "FAIL ") + label + ("" if ok or not detail else "\n      " + detail.replace("\n", "\n      ")))


def exe(name: str) -> Path:
    """The Release exe under any net9.0 target folder (viewprobe targets net9.0-windows...)."""
    hits = sorted((HARNESS / name / "bin" / "Release").glob(f"net9.0*/{name}.exe"))
    return hits[0] if hits else HARNESS / name / "bin" / "Release" / "net9.0" / f"{name}.exe"


def plugin(path: Path, masters: list[str], esm: bool = False) -> None:
    """A TES4-only plugin: HEDR, then MAST/DATA per master. Enough for every header read and for an overlay open."""
    body = b"HEDR" + struct.pack("<H", 12) + struct.pack("<fiI", 1.7, 0, 0x800)
    for m in masters:
        z = m.encode("latin-1") + b"\0"
        body += b"MAST" + struct.pack("<H", len(z)) + z + b"DATA" + struct.pack("<H", 8) + struct.pack("<Q", 0)
    head = b"TES4" + struct.pack("<IIIIHH", len(body), 1 if esm else 0, 0, 0, 44, 0)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(head + body)


def profile(inst: Path, name: str, modlist: list[str], loadorder: list[str], plugins: list[str]) -> None:
    d = inst / "profiles" / name
    d.mkdir(parents=True, exist_ok=True)
    head = "# This file was automatically generated by Mod Organizer.\n"
    (d / "modlist.txt").write_text(head + "\n".join(modlist) + "\n", encoding="utf-8")
    (d / "loadorder.txt").write_text(head + "\n".join(loadorder) + "\n", encoding="utf-8")
    (d / "plugins.txt").write_text(head + "\n".join(plugins) + "\n", encoding="utf-8")


def candidate(path: Path, base_profile: str, plugins: list[str], mods: list[str]) -> Path:
    path.write_text(json.dumps({"SchemaVersion": 1, "Name": path.stem, "BaseProfile": base_profile, "Plugins": plugins,
                                "Mods": mods, "Changes": []}), encoding="utf-8")
    return path


def run(probe: str, args: list[str], tmp: Path, prof: str, inst: Path, game: Path, work: Path) -> tuple[int, str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith("HOUSECARL_MO2") and k != "HOUSECARL_GAME_PATH"}
    env.update({"HOUSECARL_HARNESS_CONFIG": str(tmp / "harness.json"), "HOUSECARL_RUNLOG_DIR": str(tmp / "runlog"),
                "HOUSECARL_MO2_INSTANCE": inst.as_posix(), "HOUSECARL_MO2_PROFILE": prof,
                "HOUSECARL_GAME_PATH": game.as_posix()})
    work.mkdir(parents=True, exist_ok=True)
    try:
        p = subprocess.run([str(exe(probe))] + args, env=env, cwd=work, capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=180)
        return p.returncode, (p.stdout or "") + (p.stderr or "")
    except subprocess.TimeoutExpired as ex:
        return -1, f"timeout: {ex}"


def written(work: Path) -> list[str]:
    return sorted(str(p.relative_to(work)) for p in work.rglob("*") if p.is_file())


def stamps(probe: str) -> dict[str, float]:
    """The probe's own bin folder (some probes write a result next to their exe)."""
    d = exe(probe).parent
    return {str(p): p.stat().st_mtime for p in d.rglob("*") if p.is_file()} if d.exists() else {}


def touched(before: dict[str, float], after: dict[str, float]) -> list[str]:
    return sorted(Path(k).name for k, v in after.items() if before.get(k) != v)


def rows_for(cand: str, pin: list[str], child: Path) -> list[tuple[str, list[str]]]:
    """Every probe that reads --order through HarnessOrderCli.Resolve, with the arguments it needs before it reads its
    order and an output path inside its own working folder wherever it takes one."""
    return [
        ("bosprobe", ["--order", cand]),
        ("contactprobe", ["--order", cand, "--emit", "out.json"]),
        ("depprobe", ["--order", cand, "--json", "out.json"]),
        ("driftprobe", ["--order", cand, "--emit", "out.json"]),
        ("navownprobe", ["--order", cand, "--emit", "out.json"]),
        ("overlapprobe", ["--order", cand, "--emit", "out.json"]),
        ("seamprobe", ["--order", cand, "--json", "out.json"]),
        ("stateprobe", ["--order", cand, "--all", "--json", "out.json"]),
        ("switchprobe", ["--order", cand, "--json", "out.json"]),
        ("waterprobe", ["--order", cand, "--json", "out.json"]),
        ("scopeprobe", ["--order", cand, "--target", "Child.esp", "--json", "scope.json"]),
        ("lightprobe", ["--order", cand, "--json", "out.json", "--list-interiors"]),
        ("blockprobe", ["Child.esp", "--order", cand]),
        ("floorgapprobe", ["cell", "AnyCell", "--winning", "--order", cand]),
        ("motionprobe", pin + ["--order", cand, "inspect", "meshes/x.nif"]),
        ("selectprobe", ["--newcomer", str(child), "--order", cand, "--out", "sel"]),
        ("leftbehindprobe", ["--base-order", cand, "--city-order", cand, "--panel-plugin", "Child.esp",
                             "--json", "out.json"] + pin),
        ("viewprobe", ["AnyCell", "--order", cand, "--out", "view"]),
    ]


ENABLE_ROWS = [
    ("bosprobe", []),
    ("contactprobe", ["--emit", "out.json"]),
    ("depprobe", ["--json", "out.json"]),
    ("navownprobe", ["--emit", "out.json"]),
    ("overlapprobe", ["--emit", "out.json"]),
    ("seamprobe", ["--json", "out.json"]),
    ("stateprobe", ["--all", "--json", "out.json"]),
    ("switchprobe", ["--json", "out.json"]),
    ("waterprobe", ["--json", "out.json"]),
    ("scopeprobe", ["--target", "Child.esp", "--json", "scope.json"]),
]


def main() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="hc-order-input-"))
    try:
        inst, game = tmp / "instance", tmp / "game"
        plugin(game / "Data" / "Base.esm", [], esm=True)
        plugin(inst / "mods" / "ModP" / "Parent.esp", ["Base.esm"])
        plugin(inst / "mods" / "ModC" / "Child.esp", ["Base.esm", "Parent.esp"])
        plugin(inst / "mods" / "ModG" / "Ghost.esp", ["Base.esm"])
        plugin(inst / "mods" / "ModG" / "Off.esp", ["Base.esm"])
        (inst / "overwrite").mkdir(parents=True)
        (inst / "ModOrganizer.ini").write_text(f"[General]\ngamePath=@ByteArray({str(game)})\n", encoding="utf-8")
        (tmp / "harness.json").write_text(json.dumps({"instance": inst.as_posix(), "profile": "Good",
                                                      "game": game.as_posix()}), encoding="utf-8")
        order = ["Base.esm", "Parent.esp", "Off.esp", "Child.esp"]
        ticked = ["*Parent.esp", "Off.esp", "*Child.esp"]
        profile(inst, "Good", ["+ModG", "+ModC", "+ModP"], order, ticked)
        profile(inst, "Other", ["+ModG", "+ModP", "+ModC"], order, ticked)
        plugins = ["Base.esm", "Parent.esp", "Child.esp"]
        other = candidate(tmp / "cand-other.json", "Other", plugins, ["ModC", "ModP"])
        good = candidate(tmp / "cand-good.json", "Good", plugins, ["ModC", "ModP"])
        child = inst / "mods" / "ModC" / "Child.esp"
        pin = ["--instance", inst.as_posix(), "--game", game.as_posix(), "--profile", "Good"]

        def row(case: str, i: int, probe: str, args: list[str], sentence: str, label_args: list[str]):
            label = f"{case} {probe} {' '.join(a for a in label_args if not a.startswith(str(tmp)))}".strip()
            if not exe(probe).exists():
                check(False, label + ": Release build exists", str(exe(probe)))
                return None
            work = tmp / "work" / f"{case}-{i:02d}-{probe}"
            before = stamps(probe)
            code, out = run(probe, args, tmp, "Good", inst, game, work)
            files = written(work) + touched(before, stamps(probe))
            return label, code, out, out.count(sentence), files

        # 1320: --enable of a plugin loadorder.txt does not list.
        check(len(ENABLE_ROWS) == 10, "1320 row count is 10 (every probe that takes --enable)", f"{len(ENABLE_ROWS)} rows")
        for i, (probe, args) in enumerate(ENABLE_ROWS):
            got = row("1320", i, probe, ["--enable", "Ghost.esp"] + args, ENABLE_SENTENCE, ["--enable", "Ghost.esp"] + args)
            if got is None:
                continue
            label, code, out, n, files = got
            check(code == 2 and n == 1 and not files and "Unhandled exception" not in out,
                  f"{label}: exit 2, the CANNOT ENABLE sentence once, nothing written",
                  f"exit {code}; sentence x{n}; written {files}\n{out[-1200:]}")

        # 1321: --order whose BaseProfile is another profile.
        rows = rows_for(str(other), pin, child)
        check(len(rows) == 18, "1321 row count is 18 (every probe that reads --order through the shared reader)",
              f"{len(rows)} rows")
        for i, (probe, args) in enumerate(rows):
            got = row("1321", i, probe, args, PROFILE_SENTENCE, args)
            if got is None:
                continue
            label, code, out, n, files = got
            check(code == 2 and n == 1 and out.count("BaseProfile 'Other'") == 1 and not files
                  and "Unhandled exception" not in out,
                  f"{label}: exit 2, the PROFILE MISMATCH sentence once, nothing written",
                  f"exit {code}; sentence x{n}; written {files}\n{out[-1200:]}")

        # 1322: overlapprobe's scene preflight refuses the mismatch first; there is one refusal, never two.
        work = tmp / "work" / "1322-overlapprobe"
        code, out = run("overlapprobe", ["--scene-preflight", "--order", str(other), "--json", "verdict.json"],
                        tmp, "Good", inst, game, work)
        check(code == 2 and out.count("candidate BaseProfile 'Other' does not match --profile 'Good'") == 1
              and "Unhandled exception" not in out,
              "1322 overlapprobe --scene-preflight: the mismatch is refused once (its own preflight sentence), exit 2",
              f"exit {code}\n{out[-1200:]}")

        # 1323: controls - a listed plugin enables, a matching candidate resolves.
        for i, (probe, args) in enumerate(ENABLE_ROWS):
            got = row("1323", i, probe, ["--enable", "Off.esp"] + args, "CANNOT ENABLE", ["--enable", "Off.esp"] + args)
            if got is not None:
                label, code, out, n, _ = got
                check(n == 0 and "PROFILE MISMATCH" not in out and "Unhandled exception" not in out,
                      f"{label}: a listed plugin is not refused", f"exit {code}\n{out[-600:]}")
        for i, (probe, args) in enumerate(rows_for(str(good), pin, child)):
            got = row("1323", 20 + i, probe, args, "PROFILE MISMATCH", ["cand-good"] + args)
            if got is not None:
                label, code, out, n, _ = got
                check(n == 0 and "is not the BaseProfile" not in out and "Unhandled exception" not in out,
                      f"{label}: a candidate built on --profile is not refused for its profile", f"exit {code}\n{out[-600:]}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    # 1324: ordersweep recognises both sentences as a refusal, as it recognises MISSING MASTER, so an arm refused this
    # way is set aside, never read as an ordinary non-zero exit (the controller's own marker is runcontrol's
    # Validator.RefusedRe).
    import importlib.util
    lines = ["CANNOT ENABLE - 'Ghost.esp' has no load-order position: loadorder.txt does not list it, so this run would "
             "measure the order without it; switch 'Ghost.esp' on once in MO2 so loadorder.txt lists it, or give it a "
             "position in an --order candidate, then run again.",
             "PROFILE MISMATCH - candidate BaseProfile 'Other' does not match --profile 'Good' ('cand-other.json'), so "
             "its plugins and mod folders would be resolved through the lists of profile 'Good', not the profile it was "
             "built on; run with --profile 'Other', or rebuild the candidate on profile 'Good', then run again."]
    for mod_name in ("ordersweep",):
        spec = importlib.util.spec_from_file_location(f"{mod_name}_1324", HARNESS / f"{mod_name}.py")
        mod = importlib.util.module_from_spec(spec)
        sys.path.insert(0, str(HARNESS))
        try:
            spec.loader.exec_module(mod)
        finally:
            sys.path.pop(0)
        hits = [bool(mod.REFUSED_RE.search(s)) for s in lines]
        check(all(hits), f"1324 {mod_name}.REFUSED_RE recognises the CANNOT ENABLE and PROFILE MISMATCH sentences",
              f"matches {hits}")

    print(f"\n{len(PASSED)} passed, {len(FAILURES)} failed")
    return 1 if FAILURES else 0


if __name__ == "__main__":
    sys.exit(main())
