"""Known answers for the navmesh repair's write, read-back and re-check through houseCARL's server program (C2494-C2499,
C2504-C2505), on the fixture of _geometry-harness/tests/test_navmesh_repair_rules.py.

    python integration/housecarl/tests/test_navmesh_repair_write.py

The plan the real navownprobe makes on that suite's fixture (its Lab, imported, not copied) is written by houseCARL's
server program, the one in this module's build (skywright_paths.server(): Tools/housecarl-mcp/ in
integration/housecarl/bin/<Configuration>/, with its rulebook beside it), over its stdio tools housecarl_apply and
housecarl_forward; the patch is read back and the order with it re-checked by navownprobe. The app writes the same plan
through houseCARL's code in process (workbench.tests' NavRepairLaneTests); these cases keep the server's own route
checked, and they live in the module because only the module holds that program.

    2650  control: the module's build holds houseCARL's server with its rulebook (corpus.json) beside it.
    2494  the write: the plan's ops through housecarl_apply (the module's server, out_path) make one new patch holding
          exactly the planned navmeshes.
    2495  the read-back: every planned navmesh in the patch is its winner with exactly the plan applied, and every record
          the patch carries (its CELL and WRLD containers) is its winner's.
    2498  the read-back refuses a carried container that is not the winner's: the plan's ops alone carry the border cell
          (0,0) from Skyrim.esm, the navmeshes' winner, while RpD.esp wins that cell (review of Gate C part 1, finding 1).
    2499  the forward the read-back names to fix it is exactly that cell from RpD.esp; after it, the cell is RpD's.
    2496  the read-back's arm: a patch written with one unplanned edit (L5's vertex 1 moved 1 u) fails it, naming the field.
    2504  the read-back holds the patch's NAVI to RpA.esp's with exactly those two entries changed, and holds.
    2505  the read-back's NAVI arm: a patch whose NAVI also changes an entry the plan leaves (R5's) fails, naming that entry.
    2497  the re-check, by the same rule on the order with the patch added: relinked links and the ground rows go
          Holds -> Gone (repaired), L7's and SL's cut links are reported as cut, L4's as refused, and no border, link or
          ground row is created.

Probes come from this checkout's Release builds unless HC_NR_HARNESS names another build folder (as in
test_navmesh_repair_rules.py); houseCARL's rulebook generator from the pin's src (HC_NR_SRC another). HC_NR_CASES
(e.g. "2494,2497") runs those cases only.
"""

